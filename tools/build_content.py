#!/usr/bin/env python3
"""Bundle content/*.json into js/content.js (window.LWE_CONTENT), so the app boots
with a plain <script> tag and no fetch/Promise. The JSON files stay the source of truth:
edit them, then run   python3 tools/build_content.py   (and tools/validate_content.py)."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
C = os.path.join(ROOT, "content")
def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)
course = load(os.path.join(C, "course.json"))
cat = load(os.path.join(C, "catalogue.json"))
lessons = {}
for u in course["units"]:
    for lid in u["lessons"]:
        lessons[lid] = load(os.path.join(C, "lessons", lid + ".json"))
data = {"course": course, "catalogue": cat, "lessons": lessons}
# ensure_ascii keeps the file pure ASCII (\\uXXXX escapes are ES3-safe)
body = json.dumps(data, ensure_ascii=True, separators=(",", ":"), sort_keys=True)
out = os.path.join(ROOT, "js", "content.js")
with open(out, "w", encoding="ascii") as f:
    f.write("/* GENERATED by tools/build_content.py from content/*.json. Do not edit by hand. */\n")
    f.write("window.LWE_CONTENT = " + body + ";\n")
print("wrote", os.path.relpath(out, ROOT), os.path.getsize(out), "bytes,", len(lessons), "lessons")
